# Definimos una función llamada 'obtener_double' que recibe un número 
def obtener_double (n):
   # Toma ese número 'n', lo multiplica por 2 y devuelve el resultado 
    return n*2
# Llamamos a la función con el número pedido e imprimimos el resultado 
print(obtener_double(14))
print(obtener_double(0))
